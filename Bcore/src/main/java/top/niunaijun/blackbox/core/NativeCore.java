    public static int getCallingUid(int origCallingUid) {
        if (origCallingUid != BlackBoxCore.getHostUid() || Boolean.TRUE.equals(sReentrantGuard.get()))
            return origCallingUid;
        sReentrantGuard.set(true);
        try {
            int ownUid = BActivityThread.getBUid();
            if (BActivityThread.getAppPackageName() == null || ownUid <= 0) return origCallingUid;
            int pid = android.os.Binder.getCallingPid();
            if (pid == Process.myPid()) return ownUid;
            int caller = BlackBoxCore.getBActivityManager().getService()
                    .getUidForPid(pid, BActivityThread.getUserId());
            return caller > 0 ? caller : origCallingUid;
        } catch (Exception unavailable) {
            return origCallingUid;
        } finally {
            sReentrantGuard.set(false);
        }
    }

